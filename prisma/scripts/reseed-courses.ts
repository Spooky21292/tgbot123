async function clearCourseTables() {
  await prisma.quizResult.deleteMany();
  await prisma.userProgress.deleteMany();
  await prisma.quizQuestion.deleteMany();
  await prisma.quiz.deleteMany();
  await prisma.lesson.deleteMany();
  await prisma.course.deleteMany();
}

async function seedCourses() {
  for (const course of COURSES) {
    const createdCourse = await prisma.course.create({
      data: {
        title: course.title,
        slug: course.slug,
        description: course.description,
        ageGroup: course.ageGroup,
        level: course.level,
        coverImage: course.coverImage,
        isPublished: true,
        isPremium: !course.isFree
      }
    });

    for (const [index, lesson] of course.lessons.entries()) {
      await prisma.lesson.create({
        data: {
          courseId: createdCourse.id,
          title: lesson.title,
          description: lesson.description,
          videoUrl: '',
          content: lesson.content,
          order: index + 1,
          durationMinutes: 15
        }
      });
    }
  }
}

async function main() {
  await clearCourseTables();
  await seedCourses();

  console.log({
    cleared: ['quizResult', 'userProgress', 'quizQuestion', 'quiz', 'lesson', 'course'],
    seededCourses: COURSES.length,
    seededLessons: COURSES.reduce((sum, item) => sum + item.lessons.length, 0)
  });
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
